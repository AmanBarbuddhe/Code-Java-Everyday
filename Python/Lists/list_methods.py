nums = [1,2,3]

nums.append(4)  # appends a value at last of list
print(nums)

nums.insert(0,7) # l.insert(index,value) , insert element at index
print(nums)

nums.sort() # arrange in increasing order
print(nums)

#to sort in decreasing order
nums.sort(reverse=True)
print(nums)

nums.reverse() # reverses order
print(nums)